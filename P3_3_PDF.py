btn = tk.Button(root, text="GENERATE PDF REPORT - P3.3 PRO", bg="orange", fg="black", font=("Arial",12,"bold"), command=start_scan)
btn.pack(pady=10)

log = tk.Text(root, height=28, bg="black", fg="#00FF00", font=("Consolas",9))
log.pack(fill=tk.BOTH, expand=True, padx=10, pady=10)

root.mainloop()